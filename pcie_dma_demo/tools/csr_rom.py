"""Make serdes_reinit_rom.vh (the replay's write list) from the PCIe IP's serdes.csr.

usage: csr_rom.py src/serdes/serdes.csr > src/include/serdes_reinit_rom.vh
       csr_rom.py src/serdes/serdes.csr --check src/include/serdes_reinit_rom.vh

serdes.csr is written by the Gowin IP generator with the SerDes/PCIe IP. Every
write is kept, in file order, including repeats (reset then release). Some Gowin
versions spell lines "upar_wirte_driver"; they are writes too and are kept.
--check exits 1 if the .vh is not exactly what serdes.csr gives.
"""
import os
import re
import sys

LINE = re.compile(r'upar_w[a-z]*_driver\(\s*0x([0-9a-fA-F]+)\s*,\s*0x([0-9a-fA-F]+)\s*\)')


def rom(path):
    writes = []
    with open(path, encoding='utf-8') as f:
        for n, ln in enumerate(f, 1):
            if not ln.strip():
                continue
            m = LINE.search(ln)
            if not m:
                sys.exit('%s:%d: not a upar write: %s' % (path, n, ln.strip()))
            a, v = int(m.group(1), 16), int(m.group(2), 16)
            if a >> 24 or v >> 32:
                sys.exit('%s:%d: address or value out of range' % (path, n))
            writes.append((a, v))
    if not 0 < len(writes) <= 511:
        sys.exit('%d writes: expected 1..511' % len(writes))
    out = ['// Generated by tools/csr_rom.py from %s: %d writes. Do not edit.' % (os.path.basename(path), len(writes)),
           "localparam [8:0] NW = 9'd%d;" % len(writes),
           'function [55:0] wrom(input [8:0] i);',
           '    case (i)']
    out += ["        9'd%d: wrom = {24'h%06X, 32'h%08X};" % (i, a, v) for i, (a, v) in enumerate(writes)]
    out += ["        default: wrom = 56'd0;", '    endcase', 'endfunction']
    return '\n'.join(out) + '\n'


def main(argv):
    if len(argv) == 1:
        sys.stdout.write(rom(argv[0]))
    elif len(argv) == 3 and argv[1] == '--check':
        with open(argv[2], encoding='utf-8') as f:
            same = f.read() == rom(argv[0])
        print('%s %s %s' % (argv[2], 'matches' if same else 'DOES NOT match', argv[0]))
        sys.exit(0 if same else 1)
    else:
        sys.exit(__doc__)


if __name__ == '__main__':
    main(sys.argv[1:])
